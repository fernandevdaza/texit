/** Translate the (English) error strings emitted by the provider; unknown messages pass through. */
export function collabErrorText(t: TFunction, error: string): string {
  const rules: [RegExp, string][] = [
    [/^Could not join the collaboration room: ([\s\S]*)$/, 'collab.err.join'],
    [/^Collaboration message error: ([\s\S]*)$/, 'collab.err.message'],
    [/^Could not apply a remote update: ([\s\S]*)$/, 'collab.err.apply'],
    [/^A peer sent data that could not be decrypted/, 'collab.err.decrypt'],
    [/^Ignored changes from a read-only participant/, 'collab.err.rejected'],
    [/^A collaborator is using a newer version of TexIt/, 'collab.err.newer'],
  ];
  for (const [re, key] of rules) {
    const m = re.exec(error);
    if (m) return t(key, { detail: m[1] ?? '' });
  }
  return error;
}

/** Replace `{name}` placeholders of a translated string with React nodes. */
export function richText(text: string, nodes: Record<string, ReactNode>): ReactNode {
  const parts = text.split(/(\{\w+\})/g).map((part, i) => {
    const m = /^\{(\w+)\}$/.exec(part);
    return createElement(Fragment, { key: i }, m && m[1] in nodes ? nodes[m[1]] : part);
  });
  return createElement(Fragment, null, ...parts);
}
