/** Sentinel thread titles stored in IndexedDB (kept in English) → display title. */
export const NEW_CHAT_TITLE = 'New chat';
export const EXTERNAL_AGENT_TITLE = 'External agent';
export const EXTERNAL_AGENT_LABEL = 'External agent via MCP';

export function threadTitle(title: string | undefined, tr: (key: string) => string = t): string {
  if (title === NEW_CHAT_TITLE) return tr('ai.newChat');
  if (title === EXTERNAL_AGENT_TITLE) return tr('ai.externalAgent');
  return title ?? '';
}

/**
 * Extra system-prompt line asking the model to answer in the interface language.
 * Empty for English (the model already follows the user's language by default).
 */
export function languageInstruction(): string {
  return getLocale() === 'es'
    ? "The user's interface language is Spanish. Reply in Spanish unless the user writes in another language. Some requests are pre-written in English by TexIt's quick actions; still reply in Spanish to those. Never translate LaTeX code, commands, labels or the document's own text unless asked."
    : '';
}

/** Joins custom instructions with the language instruction. */
export function withLanguageInstruction(customInstructions: string | undefined): string {
  return [customInstructions?.trim(), languageInstruction()].filter(Boolean).join('\n\n');
}
